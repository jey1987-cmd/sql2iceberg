"""Generate Iceberg table DDL (Spark, format version 3) and Snowflake-managed Iceberg DDL.

Snowflake syntax follows docs.snowflake.com "CREATE ICEBERG TABLE (Snowflake as the Iceberg catalog)".
Type notes below are conservative guesses to review, not verified against a live account.
"""

from __future__ import annotations

import sqlglot
from sqlglot import exp

from .convert import UNSUPPORTED, convert_statement

# Spark 3.5 has no VARIANT/OBJECT type and rejects a bare ARRAY.
_SPARK_TYPE = {
    "VARIANT": "STRING", "OBJECT": "MAP<STRING,STRING>", "ARRAY": "ARRAY<STRING>",
    "MAP": "MAP<STRING,STRING>",
}
_SNOW_REVIEW = {
    "VARIANT": "VARIANT: check the Snowflake Iceberg data-types page; may need a structured type or VARCHAR",
    "OBJECT": "OBJECT: Iceberg tables need a structured OBJECT(...) definition",
    "ARRAY": "ARRAY: Iceberg tables need a typed ARRAY(<type>)",
    "TIMESTAMP_TZ": "TIMESTAMP_TZ: check whether Iceberg tables accept it; TIMESTAMP_LTZ may be required",
    "FLOAT": "FLOAT/DOUBLE: allowed as data, but not as a primary key",
}


def _create_tables(ddl_sql: str) -> list[exp.Create]:
    out = []
    for e in sqlglot.parse(ddl_sql, read="snowflake"):
        if isinstance(e, exp.Create) and (e.args.get("kind") or "").upper() == "TABLE" and not e.expression:
            out.append(e)
    return out


def _columns(create: exp.Create) -> tuple[str, list[exp.ColumnDef]]:
    schema = create.this
    table = schema.this
    name = ".".join(p.name for p in (table.args.get("db"), table.this) if p)
    return name, [c for c in schema.expressions if isinstance(c, exp.ColumnDef)]


def _spark_type(col: exp.ColumnDef, warnings: list[str], table: str) -> str:
    dt: exp.DataType = col.args["kind"]
    key = dt.this.name if hasattr(dt.this, "name") else str(dt.this)
    if key in _SPARK_TYPE and not dt.expressions:
        warnings.append(f"{table}.{col.name}: {key} stored as {_SPARK_TYPE[key]} (Spark 3.5 has no {key})")
        return _SPARK_TYPE[key]
    return dt.sql(dialect="spark")


def spark_iceberg_ddl(ddl_sql: str, catalog: str = "lake", namespace: str = "db",
                      format_version: int = 3) -> tuple[str, list[str]]:
    warnings: list[str] = []
    stmts = []
    for c in _create_tables(ddl_sql):
        name, cols = _columns(c)
        body = ",\n  ".join(f"{col.name} {_spark_type(col, warnings, name)}" for col in cols)
        stmts.append(
            f"CREATE TABLE IF NOT EXISTS {catalog}.{namespace}.{name.split('.')[-1]} (\n  {body}\n)\n"
            f"USING iceberg\nTBLPROPERTIES ('format-version'='{format_version}');"
        )
    return "\n\n".join(stmts) + "\n", warnings


def snowflake_iceberg_ddl(ddl_sql: str, external_volume: str | None = None, base_prefix: str = "",
                          iceberg_version: int = 3) -> tuple[str, list[str]]:
    """Snowflake-managed Iceberg tables (CATALOG = 'SNOWFLAKE'). Run in your own account."""
    warnings: list[str] = []
    stmts = []
    for c in _create_tables(ddl_sql):
        name, cols = _columns(c)
        lines = []
        for col in cols:
            dt = col.args["kind"]
            key = dt.this.name if hasattr(dt.this, "name") else str(dt.this)
            if key in _SNOW_REVIEW:
                warnings.append(f"{name}.{col.name}: {_SNOW_REVIEW[key]}")
            lines.append(f"{col.name} {dt.sql(dialect='snowflake')}")
        opts = []
        if external_volume:
            opts.append(f"EXTERNAL_VOLUME = '{external_volume}'")
        opts += ["CATALOG = 'SNOWFLAKE'", f"BASE_LOCATION = '{base_prefix}{name.split('.')[-1].lower()}/'",
                 f"ICEBERG_VERSION = {iceberg_version}"]
        stmts.append(f"CREATE ICEBERG TABLE IF NOT EXISTS {name} (\n  " + ",\n  ".join(lines) + ")\n  "
                     + "\n  ".join(opts) + ";")
    return "\n\n".join(stmts) + "\n", warnings


def pyspark_script(statements, catalog: str = "lake", namespace: str = "db") -> str:
    """A PySpark script with each converted statement as spark.sql(...). Unsupported ones are commented out."""
    out = [
        '"""Generated by sql2iceberg. Review every statement; none has been run against your data."""',
        "from pyspark.sql import SparkSession", "",
        "spark = SparkSession.builder.getOrCreate()",
        f'spark.sql("USE {catalog}.{namespace}")', "",
    ]
    for s in statements:
        if s.dynamic or s.parse_error:
            out.append(f"# {s.id}: skipped ({'built from variables' if s.dynamic else 'could not parse'})")
            continue
        r = convert_statement(s.sql)
        out.append(f"# {s.id} [{r.status}]")
        for f in r.findings:
            out.append(f"#   {f.code}: {f.message}")
        if r.status == UNSUPPORTED or r.spark_sql is None:
            out.append("# NOT GENERATED: rewrite by hand")
            out.append("# " + (r.spark_sql or s.sql).replace("\n", "\n# "))
        else:
            out.append(f'spark.sql("""{r.spark_sql}""")')
        out.append("")
    return "\n".join(out)
